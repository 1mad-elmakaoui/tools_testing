"""The command line interface, end to end through Typer's test runner.

Nothing here reaches AWS. The `push` command is covered in test_push.py with a stubbed
client, and never with real credentials.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest
import yaml
from typer.testing import CliRunner

from dqdl_gen import __version__
from dqdl_gen.cli import EXIT_BAD_CATALOG, EXIT_INVALID_DQDL, EXIT_OK, EXIT_PUSH_FAILED, app

EXIT_USAGE = 2

runner = CliRunner(env={"COLUMNS": "200", "TERM": "dumb", "NO_COLOR": "1"})


def _run(*args: str) -> Any:
    return runner.invoke(app, list(args))


# ------------------------------------------------------------------------------ basics


def test_version() -> None:
    result = _run("--version")
    assert result.exit_code == EXIT_OK
    assert __version__ in result.stdout


def test_help_states_that_generating_is_local() -> None:
    result = _run("--help")
    assert "no AWS calls" in result.stdout.replace("\n", " ")


def test_bare_invocation_shows_the_commands() -> None:
    result = _run()
    for command in ("profile", "generate", "validate", "rules", "push"):
        assert command in result.stdout


# ----------------------------------------------------------------------------- profile


def test_profile_prints_a_table(orders_csv: Path) -> None:
    result = _run("profile", str(orders_csv))
    assert result.exit_code == EXIT_OK
    assert "order_id" in result.stdout
    assert "customer_note" in result.stdout


def test_profile_json(orders_csv: Path) -> None:
    result = _run("profile", str(orders_csv), "--output", "json")
    assert result.exit_code == EXIT_OK
    payload = json.loads(result.stdout)
    assert payload["row_count"] == 500
    assert payload["column_count"] == 5
    names = [column["name"] for column in payload["columns"]]
    assert names == ["order_id", "status", "region", "amount", "customer_note"]
    amount = next(c for c in payload["columns"] if c["name"] == "amount")
    assert amount["null_count"] == 5
    assert amount["completeness"] == pytest.approx(0.99)


def test_profile_with_a_sample(orders_csv: Path) -> None:
    payload = json.loads(
        _run("profile", str(orders_csv), "--sample", "50", "--output", "json").stdout
    )
    assert payload["row_count"] == 50
    assert payload["sampled"] is True
    assert payload["row_count_is_known"] is False


def test_an_unreadable_file_is_a_usage_error(tmp_path: Path) -> None:
    result = _run("profile", str(tmp_path / "nope.csv"))
    assert result.exit_code == EXIT_USAGE
    assert "file not found" in (result.stdout + result.stderr).replace("\n", " ")


def test_an_unknown_format_is_a_usage_error(tmp_path: Path) -> None:
    target = tmp_path / "data.json"
    target.write_text("{}", encoding="utf-8")
    result = _run("profile", str(target))
    assert result.exit_code == EXIT_USAGE


def test_a_zero_sample_is_a_usage_error(orders_csv: Path) -> None:
    assert _run("profile", str(orders_csv), "--sample", "0").exit_code == EXIT_USAGE


# ---------------------------------------------------------------------------- generate


