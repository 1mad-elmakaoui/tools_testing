# ------------------------------------------------------------------------ catalog file


def test_a_custom_catalog_is_honoured(
    tmp_path: Path, raw_catalog: dict[str, Any], orders_csv: Path
) -> None:
    raw_catalog["strictness"]["balanced"]["row_count_tolerance"]["value"] = 0.5
    target = tmp_path / "dqdl.yaml"
    target.write_text(yaml.safe_dump(raw_catalog), encoding="utf-8")
    result = _run("generate", str(orders_csv), "--stdout", "--catalog-file", str(target))
    assert result.exit_code == EXIT_OK
    assert "RowCount between 250 and 750" in result.stdout


def test_a_broken_catalog_exits_three(tmp_path: Path, orders_csv: Path) -> None:
    target = tmp_path / "dqdl.yaml"
    target.write_text("schema_version: 1\n", encoding="utf-8")
    result = _run("profile", str(orders_csv), "--catalog-file", str(target))
    assert result.exit_code == EXIT_BAD_CATALOG
    assert "Error reading the catalog" in result.stderr


def test_a_missing_catalog_exits_three(tmp_path: Path) -> None:
    result = _run("rules", "--catalog-file", str(tmp_path / "absent.yaml"))
    assert result.exit_code == EXIT_BAD_CATALOG


# -------------------------------------------------------------------------------- push


def test_push_without_confirm_sends_nothing(orders_csv: Path, tmp_path: Path) -> None:
    """The guard that keeps a write command from writing by accident."""
    out = tmp_path / "orders.dqdl"
    _run("generate", str(orders_csv), "--out", str(out))
    result = _run("push", str(out), "--name", "orders-rules")
    assert result.exit_code == EXIT_PUSH_FAILED
    assert "Refusing to write to AWS without --confirm" in result.stderr
    assert "glue:CreateDataQualityRuleset" in result.stderr


def test_push_rejects_an_invalid_ruleset(tmp_path: Path) -> None:
    """Nothing invalid is ever sent to AWS, even with --confirm."""
    target = tmp_path / "bad.dqdl"
    target.write_text("Rules = [ Frobnicate > 1 ]\n", encoding="utf-8")
    result = _run("push", str(target), "--name", "x", "--confirm")
    assert result.exit_code == EXIT_INVALID_DQDL


def test_push_rejects_a_missing_file(tmp_path: Path) -> None:
    assert _run("push", str(tmp_path / "absent.dqdl"), "--name", "x").exit_code == EXIT_USAGE


def test_push_with_confirm_calls_glue_once(
    orders_csv: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The success path, with the AWS call replaced so nothing leaves the machine."""
    import dqdl_gen.push as push_module

    out = tmp_path / "orders.dqdl"
    _run("generate", str(orders_csv), "--out", str(out))

    seen: list[push_module.PushRequest] = []

    def fake_create(
        request: push_module.PushRequest, client: object | None = None
    ) -> push_module.PushResult:
        seen.append(request)
        return push_module.PushResult(name=request.name, region="eu-west-2")

    monkeypatch.setattr(push_module, "create_ruleset", fake_create)
    result = _run(
        "push",
        str(out),
        "--name",
        "orders-rules",
        "--confirm",
        "--database",
        "sales",
        "--table",
        "orders",
    )
    assert result.exit_code == EXIT_OK
    assert len(seen) == 1
    assert seen[0].name == "orders-rules"
    assert seen[0].database_name == "sales"
    assert seen[0].ruleset == out.read_text(encoding="utf-8")


def test_push_json_reports_what_was_created(
    orders_csv: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    import dqdl_gen.push as push_module

    out = tmp_path / "orders.dqdl"
    _run("generate", str(orders_csv), "--out", str(out))
    monkeypatch.setattr(
        push_module,
        "create_ruleset",
        lambda request, client=None: push_module.PushResult(request.name, "us-east-1"),
    )
    payload = json.loads(
        _run("push", str(out), "--name", "orders-rules", "--confirm", "--output", "json").stdout
    )
    assert payload == {"created": "orders-rules", "region": "us-east-1"}


def test_push_reports_a_glue_failure(
    orders_csv: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    import dqdl_gen.push as push_module

    out = tmp_path / "orders.dqdl"
    _run("generate", str(orders_csv), "--out", str(out))

    def fail(request: object, client: object | None = None) -> None:
        raise push_module.PushError("a ruleset named 'orders-rules' already exists")

    monkeypatch.setattr(push_module, "create_ruleset", fail)
    result = _run("push", str(out), "--name", "orders-rules", "--confirm")
    assert result.exit_code == EXIT_PUSH_FAILED
    assert "already exists" in result.stderr


def test_push_rejects_a_half_specified_target(orders_csv: Path, tmp_path: Path) -> None:
    out = tmp_path / "orders.dqdl"
    _run("generate", str(orders_csv), "--out", str(out))
    result = _run("push", str(out), "--name", "x", "--confirm", "--database", "sales")
    assert result.exit_code == EXIT_USAGE
    assert "both --database and --table" in (result.stdout + result.stderr).replace("\n", " ")
